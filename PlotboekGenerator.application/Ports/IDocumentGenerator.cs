using PlotboekGenerator.core.Generator.Templates;

namespace PlotboekGenerator.Application.Ports;

/// <summary>
/// Generates binary documents from export data.
/// </summary>
public interface IDocumentGenerator
{
    /// <summary>
    /// Generates a DOCX file from plotboek export data.
    /// </summary>
    /// <param name="exportData">The export data to merge into the template.</param>
    /// <param name="cancellationToken">Token to cancel the operation.</param>
    /// <returns>A result containing the generated DOCX bytes.</returns>
    Task<Result<byte[]>> GeneratePlotboekDocumentAsync(PlotboekTemplateData exportData, CancellationToken cancellationToken = default);

    /// <summary>
    /// Generates a DOCX file from plotboek export data, nudging its PAGEREF page numbers by
    /// <paramref name="corrections"/> (a per-bookmark page offset derived from a previous Google
    /// Drive render) and returning the estimator's own uncorrected bookmark data alongside the
    /// bytes, so the caller can persist it as the next sync cycle's correction baseline.
    /// </summary>
    /// <param name="exportData">The export data to merge into the template.</param>
    /// <param name="corrections">
    /// Per-bookmark page offsets to apply on top of the estimate. Pass an empty dictionary for no
    /// correction.
    /// </param>
    /// <param name="cancellationToken">Token to cancel the operation.</param>
    /// <returns>A result containing the generated bytes and the estimator's raw bookmark data.</returns>
    Task<Result<GeneratedDocument>> GeneratePlotboekDocumentWithCorrectionsAsync(
        PlotboekTemplateData exportData,
        IReadOnlyDictionary<string, int> corrections,
        CancellationToken cancellationToken = default);
}
